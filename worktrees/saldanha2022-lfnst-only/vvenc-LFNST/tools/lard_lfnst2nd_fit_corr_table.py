#!/usr/bin/env python3
"""Fit LARD-LFNST second-response correlation templates from x_theta CSV samples.

The input CSV is produced by the encoder option LardLfnst2ndVecFile.  The output
is a C++ include file consumed by source/Lib/EncoderLib/IntraSearch.cpp.
"""

from __future__ import annotations

import argparse
import csv
import glob
import math
from pathlib import Path
import sys

try:
    import numpy as np
except ImportError as exc:  # pragma: no cover - environment guard
    raise SystemExit("numpy is required for fitting the correlation table") from exc


DIM = 48
VALID_DIMS = {16, 48}


class Accumulator:
    def __init__(self) -> None:
        self.n = 0
        self.sum = np.zeros(DIM, dtype=np.float64)
        self.cross = np.zeros((DIM, DIM), dtype=np.float64)

    def add(self, values: np.ndarray, dim: int) -> None:
        vec = np.zeros(DIM, dtype=np.float64)
        vec[:dim] = values[:dim]
        self.n += 1
        self.sum += vec
        self.cross += np.outer(vec, vec)


def lat_bucket(abs_lat_deg: float) -> int:
    if abs_lat_deg < 30.0:
        return 0
    if abs_lat_deg < 50.0:
        return 1
    if abs_lat_deg < 70.0:
        return 2
    return 3


def parse_int(row: dict[str, str], name: str, default: int | None = None) -> int:
    value = row.get(name, "")
    if value == "":
        if default is None:
            raise ValueError(f"missing {name}")
        return default
    return int(float(value))


def parse_float(row: dict[str, str], name: str, default: float = 0.0) -> float:
    value = row.get(name, "")
    return default if value == "" else float(value)


def expand_inputs(patterns: list[str]) -> list[Path]:
    paths: list[Path] = []
    for pattern in patterns:
        matches = glob.glob(pattern)
        if matches:
            paths.extend(Path(m) for m in matches)
        else:
            paths.append(Path(pattern))
    return paths


def read_samples(paths: list[Path], pooled_fallbacks: bool) -> dict[tuple[int, int, int, int, int], Accumulator]:
    groups: dict[tuple[int, int, int, int, int], Accumulator] = {}

    for path in paths:
        with path.open("r", newline="") as fp:
            reader = csv.DictReader(fp)
            for row_idx, row in enumerate(reader, start=2):
                try:
                    dim = parse_int(row, "trSize")
                    if dim not in VALID_DIMS:
                        continue
                    values = np.array([parse_float(row, f"x{i:02d}") for i in range(DIM)], dtype=np.float64)
                    lat = parse_int(row, "latBucket", lat_bucket(parse_float(row, "absLatDeg")))
                    mode = parse_int(row, "modeGroup")
                    size = parse_int(row, "sizeGroup")
                    sb_class = parse_int(row, "sbClass", 1 if parse_int(row, "sbSize") > 4 else 0)
                except Exception as exc:
                    raise SystemExit(f"{path}:{row_idx}: cannot parse vector row: {exc}") from exc

                key = (lat, mode, size, sb_class, dim)
                groups.setdefault(key, Accumulator()).add(values, dim)

                if pooled_fallbacks:
                    pooled_key = (lat, -1, -1, -1, dim)
                    groups.setdefault(pooled_key, Accumulator()).add(values, dim)

    return groups


def fit_corr(acc: Accumulator, dim: int, shrink: float, clip: float, positive_only: bool) -> np.ndarray:
    mean = acc.sum / max(1, acc.n)
    cov = acc.cross / max(1, acc.n) - np.outer(mean, mean)
    var = np.maximum(np.diag(cov), 0.0)
    denom = np.sqrt(np.outer(var, var))
    corr = np.zeros((DIM, DIM), dtype=np.float64)
    valid = denom > 1e-12
    corr[valid] = cov[valid] / denom[valid]
    corr = np.nan_to_num(corr, nan=0.0, posinf=0.0, neginf=0.0)
    corr = np.clip(corr, -clip, clip)
    if positive_only:
        corr = np.maximum(corr, 0.0)
    corr *= shrink
    np.fill_diagonal(corr, 1.0)
    corr[dim:, :] = 0.0
    corr[:, dim:] = 0.0
    return corr


def write_inc(
    output: Path,
    groups: dict[tuple[int, int, int, int, int], Accumulator],
    min_samples: int,
    shrink: float,
    clip: float,
    positive_only: bool,
) -> int:
    emitted = 0
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("w", newline="\n") as fp:
        fp.write("// Auto-generated by tools/lard_lfnst2nd_fit_corr_table.py. Do not edit by hand.\n")
        fp.write("// Fields: latBucket, modeGroup, sizeGroup, sbClass, dim, samples, corr[48][48].\n")
        for key in sorted(groups):
            acc = groups[key]
            if acc.n < min_samples:
                continue
            lat, mode, size, sb_class, dim = key
            corr = fit_corr(acc, dim, shrink, clip, positive_only)
            quant = np.rint(corr * 32767.0).astype(np.int32)
            quant = np.clip(quant, -32767, 32767)

            fp.write(f"// lat={lat} mode={mode} size={size} sb={sb_class} dim={dim} samples={acc.n}\n")
            fp.write(f"{{ {lat}, {mode}, {size}, {sb_class}, {dim}, {acc.n},\n")
            fp.write("  {\n")
            for r in range(DIM):
                row = ", ".join(str(int(v)) for v in quant[r])
                fp.write(f"    {{ {row} }}{',' if r + 1 < DIM else ''}\n")
            fp.write("  }\n")
            fp.write("},\n")
            emitted += 1
        fp.write("{ -1, -1, -1, -1, 0, 0, {} },\n")
    return emitted


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("inputs", nargs="+", help="LardLfnst2ndVecFile CSV path(s), glob patterns accepted")
    parser.add_argument("-o", "--output", default="source/Lib/EncoderLib/LardLfnst2ndCorrTable.inc")
    parser.add_argument("--min-samples", type=int, default=64)
    parser.add_argument("--shrink", type=float, default=0.75, help="off-diagonal shrinkage multiplier")
    parser.add_argument("--clip", type=float, default=0.95)
    parser.add_argument("--positive-only", action="store_true")
    parser.add_argument("--pooled-fallbacks", action="store_true", help="also emit latitude/dimension pooled fallback rows")
    args = parser.parse_args(argv)

    if args.min_samples <= 0:
        raise SystemExit("--min-samples must be positive")
    if not (0.0 <= args.shrink <= 1.0):
        raise SystemExit("--shrink must be in [0,1]")
    if not (0.0 < args.clip <= 0.99):
        raise SystemExit("--clip must be in (0,0.99]")

    paths = expand_inputs(args.inputs)
    missing = [str(p) for p in paths if not p.exists()]
    if missing:
        raise SystemExit(f"missing input CSV(s): {', '.join(missing)}")

    groups = read_samples(paths, args.pooled_fallbacks)
    emitted = write_inc(Path(args.output), groups, args.min_samples, args.shrink, args.clip, args.positive_only)
    print(f"read {sum(acc.n for acc in groups.values())} grouped samples, emitted {emitted} table entries -> {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
