import hashlib
import json
import math
import os
import re
import subprocess
import tempfile
from pathlib import Path
from typing import Dict, List, Union


_METRIC_HEADER = (
    "Frame#",
    "PSNR_Y",
    "PSNR_U",
    "PSNR_V",
    "SPSNR_NN_Y",
    "SPSNR_NN_U",
    "SPSNR_NN_V",
    "WSPSNR_Y",
    "WSPSNR_U",
    "WSPSNR_V",
    "CPP-PSNR_Y",
    "CPP-PSNR_U",
    "CPP-PSNR_V",
)
_OUTPUT_PREFIXES = ("PSNR", "S", "WS", "CPP")
_COMPONENTS = ("Y", "U", "V")
_FRAME_RE = re.compile(r"^\s*Frame\s*:\s*(\d+)\b", re.MULTILINE)
PathLike = Union[str, os.PathLike]


def build_360convert_command(
    executable: PathLike,
    config_path: PathLike,
) -> List[str]:
    """Build the official 360Lib 13.6 command using a generated cfg file."""
    return [str(executable), "-c", str(config_path)]


def build_360convert_config_text(
    original: PathLike,
    reconstruction: PathLike,
    sphere_file: PathLike,
    width: int,
    height: int,
    fps: int,
    frames: int,
    original_bitdepth: int,
    reconstruction_bitdepth: int,
) -> str:
    """Build the explicit 360Lib 13.6 ERP quality-metric cfg text."""
    settings = [
        ("InputFile", str(reconstruction)),
        ("RefFile", str(original)),
        ("SphFile", str(sphere_file)),
        ("SourceWidth", str(width)),
        ("SourceHeight", str(height)),
        ("InputBitDepth", str(reconstruction_bitdepth)),
        ("OutputBitDepth", str(reconstruction_bitdepth)),
        ("InternalBitDepth", str(reconstruction_bitdepth)),
        ("ReferenceBitDepth", str(original_bitdepth)),
        ("InputChromaFormat", "420"),
        ("OutputChromaFormat", "420"),
        ("ReferenceChromaFormat", "420"),
        ("InputGeometryType", "0"),
        ("CodingGeometryType", "0"),
        ("ReferenceGeometryType", "0"),
        ("SourceFPStructure", "1 1 0 0"),
        ("CodingFPStructure", "1 1 0 0"),
        ("ReferenceFPStructure", "1 1 0 0"),
        ("CodingFaceWidth", str(width)),
        ("CodingFaceHeight", str(height)),
        ("ReferenceFaceWidth", str(width)),
        ("ReferenceFaceHeight", str(height)),
        ("CPP_Width", str(width)),
        ("CPP_Height", str(height)),
        ("PSNR", "1"),
        ("SPSNR_NN", "1"),
        ("SPSNR_I", "0"),
        ("WSPSNR", "1"),
        ("CPP_PSNR", "1"),
        ("InterpolationMethodY", "5"),
        ("InterpolationMethodC", "4"),
        ("ChromaSampleLocType", "0"),
        ("OutputChromaSampleLocType", "0"),
        ("ReferenceChromaSampleLocType", "0"),
        ("FramesToBeEncoded", str(frames)),
        ("FrameRate", str(fps)),
    ]
    lines = ["# Generated by official_360lib_metrics.py"]
    lines.extend(f"{name:<29}: {value}" for name, value in settings)
    return "\n".join(lines) + "\n"


def sha256_file(path: PathLike) -> str:
    digest = hashlib.sha256()
    with Path(path).open("rb") as source:
        for block in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _combined_console_output(stdout: str, stderr: str) -> str:
    parts = [text.rstrip("\n") for text in (stdout, stderr) if text]
    return "\n".join(parts) + ("\n" if parts else "")


def _write_json_atomically(output: Path, payload: Dict[str, object]) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    temporary_path = None
    try:
        with tempfile.NamedTemporaryFile(
            "w",
            encoding="utf-8",
            delete=False,
            dir=output.parent,
            prefix=output.name + ".",
            suffix=".tmp",
        ) as temporary:
            temporary_path = Path(temporary.name)
            json.dump(payload, temporary, indent=2, sort_keys=True)
            temporary.write("\n")
        temporary_path.replace(output)
    finally:
        if temporary_path is not None and temporary_path.exists():
            temporary_path.unlink()


def run_360lib_metrics(
    *,
    executable: PathLike,
    original: PathLike,
    reconstruction: PathLike,
    sphere_file: PathLike,
    width: int,
    height: int,
    fps: int,
    frames: int,
    original_bitdepth: int,
    reconstruction_bitdepth: int,
    log_path: PathLike,
    parsed_json_path: PathLike,
) -> Dict[str, object]:
    """Run official metrics, retain its log, and atomically persist parsed data."""
    log = Path(log_path)
    cfg_path = log.with_suffix(".cfg")
    cfg_path.parent.mkdir(parents=True, exist_ok=True)
    config_text = build_360convert_config_text(
        original,
        reconstruction,
        sphere_file,
        width,
        height,
        fps,
        frames,
        original_bitdepth,
        reconstruction_bitdepth,
    )
    cfg_path.write_text(config_text, encoding="utf-8")
    command = build_360convert_command(executable, cfg_path)
    executable_sha256 = sha256_file(executable)
    sphere_sha256 = sha256_file(sphere_file)
    config_sha256 = hashlib.sha256(config_text.encode("utf-8")).hexdigest()
    completed = subprocess.run(command, capture_output=True, text=True, check=False)
    console_output = _combined_console_output(completed.stdout, completed.stderr)

    log.parent.mkdir(parents=True, exist_ok=True)
    log.write_text(console_output, encoding="utf-8")
    if completed.returncode != 0:
        raise RuntimeError(f"360ConvertApp exited with exit code {completed.returncode}")

    parsed = parse_360lib_metrics(console_output, expected_frames=frames)
    payload: Dict[str, object] = {
        "backend": "360Lib13_6",
        "executable_sha256": executable_sha256,
        "sphere_sha256": sphere_sha256,
        "config_path": str(cfg_path),
        "config_sha256": config_sha256,
        "config": config_text,
        "command": command,
    }
    payload.update(parsed)

    output = Path(parsed_json_path)
    _write_json_atomically(output, payload)
    return payload


def _find_metric_header(lines: List[str]) -> int:
    for index, line in enumerate(lines):
        tokens = tuple(token for token in line.split() if token != "|")
        if tokens and tokens[0] == "Frame#":
            if tokens == _METRIC_HEADER:
                return index
            raise ValueError(
                "unexpected 360Lib metric header; expected enabled order "
                "PSNR, SPSNR_NN, WSPSNR, CPP-PSNR"
            )
    raise ValueError("360Lib metric header not found")


def _find_average_values(lines: List[str]) -> List[float]:
    try:
        average_index = next(
            index for index, line in enumerate(lines) if line.strip() == "Average PSNRS"
        )
    except StopIteration as exc:
        raise ValueError("Average PSNRS section not found") from exc

    for line in lines[average_index + 1 :]:
        if not re.search(r"\d|(?i:\bnan\b|\binf(?:inity)?\b)", line):
            continue
        tokens = line.replace("|", " ").split()
        try:
            values = [float(token) for token in tokens]
        except ValueError as exc:
            raise ValueError("Average PSNRS contains a non-numeric value") from exc
        if len(values) != 12:
            raise ValueError(
                f"Average PSNRS must contain exactly 12 values, parsed {len(values)}"
            )
        if not all(math.isfinite(value) for value in values):
            raise ValueError("Average PSNRS contains a non-finite value")
        return values

    raise ValueError("Average PSNRS does not contain a numeric averages line")


def parse_360lib_metrics(
    text: str, expected_frames: int
) -> Dict[str, Union[int, float]]:
    """Parse the enabled 360Lib 13.6 PSNR metric groups from console output."""
    lines = text.splitlines()
    _find_metric_header(lines)

    frame_count = len(_FRAME_RE.findall(text))
    if frame_count != expected_frames:
        raise ValueError(f"expected {expected_frames} frames, parsed {frame_count}")

    values = _find_average_values(lines)
    metrics: Dict[str, Union[int, float]] = {"frame_count": frame_count}
    for index, value in enumerate(values):
        group = _OUTPUT_PREFIXES[index // len(_COMPONENTS)]
        component = _COMPONENTS[index % len(_COMPONENTS)]
        metrics[f"360Lib13_6_{group}_{component}"] = value
    return metrics
