#!/usr/bin/env python3
"""Generate the Skip21 Stage-1/Stage-2 analytical theory table."""
from __future__ import annotations

import argparse
import math
import sys
from dataclasses import dataclass
from pathlib import Path

import numpy as np


TOOLS = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(TOOLS))

from compute_lfnst_theory_stats import parse_rom_lfnst
from tools.lard_lfnst.generate_lard_lfnst_cov_table import (
    LAT_BINS,
    SIZES,
    covariance_roi,
    zero_out_size,
)


MODE_GROUPS = range(6)
QP_BUCKETS = (19, 24, 29, 34)
Q = 1024
EPS = 1e-12


@dataclass(frozen=True)
class TheoryEntry:
    lat_bin: int
    size_id: int
    mode_group: int
    set_idx: int
    transpose: int
    qp_bucket: int
    support_ratio_q: int
    ox_q: int
    diag_dominance_q: int
    g1_cov_q: int
    g2_cov_q: int
    gmax_cov_q: int
    diff_cov_q: int


def quantize_unit_interval(value: float) -> int:
    return int(max(0, min(Q, round(value * Q))))


def support_ratio_q(width: int, height: int, theta_deg: float) -> int:
    support_cols = min(width, 4 if min(width, height) == 4 else 8)
    cos_q = int(max(0.0, math.cos(math.radians(abs(theta_deg)))) * Q + 0.5)
    effective_cols = max(1, (support_cols * cos_q) >> 10)
    return int(max(0, min(Q, (effective_cols * Q + (support_cols >> 1)) // support_cols)))


def covariance_weak_coupling_metrics(sigma_x: np.ndarray) -> tuple[int, int]:
    diag = np.maximum(np.diag(sigma_x), 0.0)
    denom = np.sqrt(np.maximum(diag[:, None] * diag[None, :], EPS))
    corr = np.abs(sigma_x / denom)
    np.fill_diagonal(corr, 0.0)
    k = sigma_x.shape[0]
    ox = float(corr.sum() / max(1, k * (k - 1)))
    diag_dominance = float(np.sum(np.abs(np.diag(sigma_x))) / (np.sum(np.abs(sigma_x)) + EPS))
    return quantize_unit_interval(ox), quantize_unit_interval(diag_dominance)


def candidate_response_metrics(
    sigma_x: np.ndarray,
    lfnst8: np.ndarray,
    lfnst4: np.ndarray,
    width: int,
    height: int,
    set_idx: int,
) -> tuple[int, int, int, int]:
    sb_size = 8 if width >= 8 and height >= 8 else 4
    k_in = 48 if sb_size == 8 else 16
    out_n = zero_out_size(width, height)
    source = lfnst8 if sb_size == 8 else lfnst4
    trace_x = float(np.trace(sigma_x))
    values: list[int] = []
    for cand in range(2):
        s_full = source[set_idx, cand, :16, :k_in].astype(np.float64)
        sigma_y = s_full @ sigma_x @ s_full.T
        diag_y = np.maximum(np.diag(sigma_y), 0.0)
        zero_energy = float(np.sum(diag_y[out_n:16]))
        values.append(quantize_unit_interval(zero_energy / (trace_x + EPS)))
    g1, g2 = values
    return g1, g2, max(g1, g2), abs(g1 - g2)


def generate_entries(rom_lfnst: Path) -> list[TheoryEntry]:
    lfnst8, lfnst4, _, _ = parse_rom_lfnst(rom_lfnst)
    entries: list[TheoryEntry] = []
    for lat_bin, theta in enumerate(LAT_BINS):
        for size_id, (width, height) in enumerate(SIZES):
            sigma_x_by_transpose = {
                transpose: covariance_roi(width, height, theta, bool(transpose))
                for transpose in (0, 1)
            }
            for transpose, sigma_x in sigma_x_by_transpose.items():
                ox_q, diag_q = covariance_weak_coupling_metrics(sigma_x)
                support_q = support_ratio_q(width, height, theta)
                for set_idx in range(4):
                    g1, g2, gmax, diff = candidate_response_metrics(
                        sigma_x, lfnst8, lfnst4, width, height, set_idx
                    )
                    for mode_group in MODE_GROUPS:
                        for qp_bucket in QP_BUCKETS:
                            entries.append(
                                TheoryEntry(
                                    lat_bin=lat_bin,
                                    size_id=size_id,
                                    mode_group=mode_group,
                                    set_idx=set_idx,
                                    transpose=transpose,
                                    qp_bucket=qp_bucket,
                                    support_ratio_q=support_q,
                                    ox_q=ox_q,
                                    diag_dominance_q=diag_q,
                                    g1_cov_q=g1,
                                    g2_cov_q=g2,
                                    gmax_cov_q=gmax,
                                    diff_cov_q=diff,
                                )
                            )
    return entries


def render(entries: list[TheoryEntry]) -> str:
    lines = [
        "#ifndef LARD_LFNST_SKIP21_THEORY_TABLE_INC",
        "#define LARD_LFNST_SKIP21_THEORY_TABLE_INC",
        "",
        "// Auto-generated by tools/lard_lfnst/generate_skip21_theory_table.py. Do not edit manually.",
        "// Metrics are quantized by 1024: supportRatioQ, oxQ, diagDominanceQ, g*CovQ.",
        "struct LardLfnstSkip21TheoryEntry",
        "{",
        "  int8_t  latBin;",
        "  int8_t  sizeId;",
        "  int8_t  modeGroup;",
        "  int8_t  setIdx;",
        "  int8_t  transpose;",
        "  int8_t  qpBucket;",
        "  int16_t supportRatioQ;",
        "  int16_t oxQ;",
        "  int16_t diagDominanceQ;",
        "  int16_t g1CovQ;",
        "  int16_t g2CovQ;",
        "  int16_t gmaxCovQ;",
        "  int16_t diffCovQ;",
        "};",
        "",
        "static const LardLfnstSkip21TheoryEntry g_lardLfnstSkip21TheoryTable[] =",
        "{",
    ]
    for entry in entries:
        lines.append(
            "  { "
            f"{entry.lat_bin}, {entry.size_id}, {entry.mode_group}, {entry.set_idx}, "
            f"{entry.transpose}, {entry.qp_bucket}, {entry.support_ratio_q}, "
            f"{entry.ox_q}, {entry.diag_dominance_q}, {entry.g1_cov_q}, "
            f"{entry.g2_cov_q}, {entry.gmax_cov_q}, {entry.diff_cov_q} "
            "},"
        )
    lines.extend(
        [
            "};",
            "",
            f"#define LARD_LFNST_SKIP21_THEORY_TABLE_SIZE {len(entries)}",
            "",
            "#endif",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--rom-lfnst", type=Path, default=Path("source/Lib/CommonLib/Rom.cpp"))
    parser.add_argument(
        "--out",
        type=Path,
        default=Path("source/Lib/EncoderLib/LardLfnstSkip21TheoryTable.inc"),
    )
    args = parser.parse_args()

    entries = generate_entries(args.rom_lfnst)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    with args.out.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(render(entries))
    print(f"generated {len(entries)} Skip21 theory entries at {args.out}")


if __name__ == "__main__":
    main()
