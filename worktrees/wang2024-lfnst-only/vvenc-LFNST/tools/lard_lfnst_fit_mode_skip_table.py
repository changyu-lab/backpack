#!/usr/bin/env python3
"""Fit a mode-level high-confidence no-LFNST table.

This is the first-level pruning table for LardLfnstSkip=8.  It uses only
features available before entering full LFNST RDO: QP, block size group,
intra-mode group and latitude bucket.  Labels come from full-RDO block rows
with j0/j1/j2 costs.
"""

from __future__ import annotations

import argparse
import csv
import json
from collections import Counter, defaultdict
from pathlib import Path

import numpy as np
import pandas as pd


USECOLS = ["w", "h", "qp", "intraMode", "absLatDeg", "j0", "j1", "j2"]


def size_group(w: np.ndarray, h: np.ndarray) -> np.ndarray:
    area = w * h
    mn = np.minimum(w, h)
    mx = np.maximum(w, h)
    return np.select([area <= 16, area <= 32, area <= 64, area <= 256, area <= 1024, mx >= 4 * mn],
                     [0, 1, 2, 3, 4, 6], default=5).astype(np.int16)


def mode_group(mode: np.ndarray) -> np.ndarray:
    return np.select([mode == 0, mode == 1, mode <= 17, mode <= 34, mode <= 50],
                     [0, 1, 2, 3, 4], default=5).astype(np.int16)


def lat_bucket(abs_lat: np.ndarray) -> np.ndarray:
    return np.select([abs_lat < 30, abs_lat < 50, abs_lat < 70], [0, 1, 2], default=3).astype(np.int16)


def pack_key(qp: int, sg: int, mg: int, lb: int) -> int:
    return (((qp * 7 + sg) * 6 + mg) * 4 + lb)


def aggregate(paths: list[Path], chunksize: int) -> dict[tuple[int, int, int, int], np.ndarray]:
    agg: dict[tuple[int, int, int, int], np.ndarray] = defaultdict(lambda: np.zeros(5, dtype=np.float64))
    for path in paths:
        for df in pd.read_csv(path, usecols=USECOLS, chunksize=chunksize):
            for col in USECOLS:
                df[col] = pd.to_numeric(df[col], errors="coerce")
            valid = (
                np.isfinite(df["j0"]) & np.isfinite(df["j1"]) & np.isfinite(df["j2"]) &
                (df["j0"] > 0) & (np.abs(df["j0"]) < 1.0e100) &
                (np.abs(df["j1"]) < 1.0e100) & (np.abs(df["j2"]) < 1.0e100)
            )
            df = df[valid]
            if not len(df):
                continue
            j0 = df["j0"].to_numpy(np.float64)
            j1 = df["j1"].to_numpy(np.float64)
            j2 = df["j2"].to_numpy(np.float64)
            costs = np.stack([j0, j1, j2], axis=1)
            best = np.argmin(costs, axis=1)
            bestc = costs[np.arange(len(df)), best]
            loss0 = np.maximum(0.0, (j0 - bestc) / np.maximum(j0, 1.0))
            tmp = pd.DataFrame({
                "qp": df["qp"].to_numpy(np.int16),
                "sg": size_group(df["w"].to_numpy(np.int32), df["h"].to_numpy(np.int32)),
                "mg": mode_group(df["intraMode"].to_numpy(np.int32)),
                "lb": lat_bucket(df["absLatDeg"].to_numpy(np.float64)),
                "n": 1,
                "false": (best != 0).astype(np.int8),
                "loss": loss0,
                "g1": (j0 - j1) / np.maximum(j0, 1.0),
                "g2": (j0 - j2) / np.maximum(j0, 1.0),
            })
            grouped = tmp.groupby(["qp", "sg", "mg", "lb"], sort=False).sum(numeric_only=True)
            for key, row in grouped.iterrows():
                a = agg[key]
                a[0] += row["n"]
                a[1] += row["false"]
                a[2] += row["loss"]
                a[3] += row["g1"]
                a[4] += row["g2"]
    return agg


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("block_csv", nargs="+", type=Path)
    ap.add_argument("--include-out", type=Path, required=True)
    ap.add_argument("--json-out", type=Path)
    ap.add_argument("--csv-out", type=Path)
    ap.add_argument("--chunksize", type=int, default=400000)
    ap.add_argument("--min-samples", type=int, default=300)
    ap.add_argument("--max-mean-loss", type=float, default=0.005)
    ap.add_argument("--max-false-rate", type=float, default=0.30)
    args = ap.parse_args()

    agg = aggregate(args.block_csv, args.chunksize)
    rows = []
    skipped_samples = 0
    skipped_false = 0
    skipped_loss = 0.0
    for key, a in sorted(agg.items(), key=lambda kv: pack_key(*kv[0])):
        n = int(a[0])
        if n < args.min_samples:
            continue
        false_rate = a[1] / a[0]
        mean_loss = a[2] / a[0]
        if false_rate <= args.max_false_rate and mean_loss <= args.max_mean_loss:
            rows.append({
                "key": pack_key(*key),
                "samples": n,
                "falseRate": float(false_rate),
                "meanLoss": float(mean_loss),
                "meanGain1": float(a[3] / a[0]),
                "meanGain2": float(a[4] / a[0]),
            })
            skipped_samples += n
            skipped_false += int(a[1])
            skipped_loss += float(a[2])

    with args.include_out.open("w", encoding="utf-8", newline="\n") as fh:
        fh.write("// Generated by tools/lard_lfnst_fit_mode_skip_table.py\n")
        fh.write(f"// minSamples={args.min_samples}, maxMeanLoss={args.max_mean_loss:g}, maxFalseRate={args.max_false_rate:g}, sourceFiles={len(args.block_csv)}\n")
        fh.write("// Key: qp,size,mode,latitude. Fields: packedKey, meanGain1, meanGain2\n")
        for row in rows:
            fh.write("  { %d, %.9g, %.9g },\n" % (row["key"], row["meanGain1"], row["meanGain2"]))

    summary = {
        "entries": len(rows),
        "sourceFiles": len(args.block_csv),
        "minSamples": args.min_samples,
        "maxMeanLoss": args.max_mean_loss,
        "maxFalseRate": args.max_false_rate,
        "skippedSamplesInFit": skipped_samples,
        "falseRateInSkipped": skipped_false / skipped_samples if skipped_samples else 0.0,
        "meanLossInSkipped": skipped_loss / skipped_samples if skipped_samples else 0.0,
    }
    if args.json_out:
        args.json_out.write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    if args.csv_out:
        with args.csv_out.open("w", newline="", encoding="utf-8") as fh:
            writer = csv.DictWriter(fh, fieldnames=["key", "samples", "falseRate", "meanLoss", "meanGain1", "meanGain2"])
            writer.writeheader()
            writer.writerows(rows)
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
